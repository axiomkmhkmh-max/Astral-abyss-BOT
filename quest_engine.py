def chapter_for_level(level: int) -> dict | None:
    for ch in MAIN_CHAPTERS:
        if ch["level_wall"] == level:
            return ch
    return None

def chapter_by_num(num: int) -> dict | None:
    for ch in MAIN_CHAPTERS:
        if ch["num"] == num:
            return ch
    return None

def next_chapter_for(player: dict) -> dict | None:
    done = player.get("main_chapter", 0)
    lvl  = player.get("level", 1)
    for ch in MAIN_CHAPTERS:
        if ch["num"] == done + 1 and lvl >= ch["level_wall"]:
            return ch
    return None


def story_new_chapter_available(player: dict) -> dict | None:
    """اگه بازیکن الان وسطِ هیچ فصلی نیست (quest_node خالیه) و یه فصلِ
    نوشته‌شده‌ی جدید طبق سطحش باز شده ولی هنوز شروعش نکرده، اون فصل رو
    برمی‌گردونه — وگرنه None. برای بج «🆕» روی دکمه و یادآوری‌های پنل/
    لول‌آپ استفاده می‌شه."""
    if player.get("quest_node"):
        return None
    ch = next_chapter_for(player)
    if ch and ch.get("written"):
        return ch
    return None


