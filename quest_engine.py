import random

RESONANCE_MIN, RESONANCE_MAX = -100, 100

def clamp_resonance(v: int) -> int:
    return max(RESONANCE_MIN, min(RESONANCE_MAX, v))

def resonance_label(v: int) -> str:
    if v >= 40:  return "✨ روشنایی (Light)"
    if v <= -40: return "🌑 خلأ (Void)"
    return "⚖️ در تعادل"


