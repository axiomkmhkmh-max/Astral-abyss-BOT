# ─── کدکس پژواک‌ها (Character Codex) ────────────────────────────
def mark_character_seen(player: dict, char_name: str):
    """هروقت یه کاراکتر به بازیکن اختصاص داده می‌شه (ساخت اولیه، رفورج،
    ادمین) صداش می‌زنیم تا تو کدکس به‌عنوان «دیده‌شده» علامت بخوره."""
    if not char_name:
        return
    seen = player.setdefault("characters_seen", [])
    if char_name not in seen:
        seen.append(char_name)


def codex_text(player: dict) -> str:
    from characters import ALL_CHARACTERS, RARITY_EMOJI
    seen = set(player.get("characters_seen", []))
    current = player.get("character")
    if current:
        seen.add(current)

    by_rarity = {"mythic": [], "special": [], "legendary": [], "rare": [], "common": []}
    for name, data in ALL_CHARACTERS.items():
        r = data.get("rarity", "common")
        by_rarity.setdefault(r, []).append(name)

    lines = ["📖 **کدکس پژواک‌ها**\n"]
    total_seen = len(seen & set(ALL_CHARACTERS.keys()))
    lines.append(f"📊 مجموع: {total_seen}/{len(ALL_CHARACTERS)} پژواک شناخته‌شده\n")

    rarity_order = [("mythic", "🌌 اسطوره‌ای"), ("special", "👑 ویژه"), ("legendary", "🌟 افسانه‌ای"),
                    ("rare", "💠 کمیاب"), ("common", "⚔️ معمولی")]
    for key, label in rarity_order:
        names = by_rarity.get(key, [])
        if not names:
            continue
        found = [n for n in names if n in seen]
        lines.append(f"{label}: {len(found)}/{len(names)}")
        if found:
            shown = found[:10]
            lines.append("   " + "، ".join(f"✅ {n}" for n in shown))
            if len(found) > 10:
                lines.append(f"   ... و {len(found)-10} تای دیگه")
        lines.append("")

    lines.append("💡 پیشینه‌ی کاملِ پژواک‌های ویژه/افسانه‌ای رو موقعِ ساختِ کاراکتر می‌بینی؛ هرچی سطحت بالاتر بره، بیشترش برات باز می‌شه.")
    return "\n".join(lines)

# ─── اپیلوگِ پیوندِ کامل (Character Epilogue Quest) ──────────────
# وقتی «پیوندِ روحیِ» کاتانا (katana_core.py → bond_level) به حداکثر
# برسه، داستانِ پس‌زمینه‌ی همون پژواک (که از قبل تو CHARACTER_LORE
# نوشته شده) به‌عنوانِ یه اپیلوگِ نمایشی رونمایی می‌شه — این همون
# «کوئستِ جانبیِ کاراکتر» است، فقط به‌جای مراحلِ جداگونه، پاداشِ
# نهاییِ رسیدن به اوجِ پیوند با همون کاراکتره.
EPILOGUE_REWARD_ZEN = 5000

def check_epilogue(player: dict, bond_result: dict) -> str | None:
    if not bond_result or not bond_result.get("leveled") or bond_result.get("new_level") != 10:
        return None
    char_name = player.get("character")
    if not char_name:
        return None
    seen = player.setdefault("epilogues_seen", [])
    if char_name in seen:
        return None
    seen.append(char_name)

    lore = CHARACTER_LORE.get(char_name) or MYTHIC_LORE.get(char_name)
    backstory = lore["backstory"] if lore else (
        f"پیوندت با {char_name} به اوجش رسید. هرچند رازش هنوز کامل روشن نشده..."
    )
    title = f"🔗 همراهِ ابدیِ {char_name}"
    player.setdefault("titles_unlocked", []).append(title)
    player["zen"] = player.get("zen", 0) + EPILOGUE_REWARD_ZEN

    return (
        f"\n\n📖 **اپیلوگ: پیوندِ کامل با {char_name}**\n\n"
        f"{backstory}\n\n"
        f"🏅 عنوانِ جدید: {title}\n"
        f"💰 +{EPILOGUE_REWARD_ZEN:,} Zen"
    )


