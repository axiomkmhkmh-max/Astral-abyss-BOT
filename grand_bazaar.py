def _pick_no_repeat(pool: list[str], last: str | None) -> str:
    """یه خط رندوم از استخر برمی‌گردونه، سعی می‌کنه از تکرارِ خطِ قبلی جلوگیری کنه."""
    if not pool:
        return ""
    if len(pool) == 1:
        return pool[0]
    choices = [line for line in pool if line != last]
    return random.choice(choices or pool)


def npc_line(npc: dict, category: str, last: str | None = None) -> str:
    return _pick_no_repeat(npc.get(category, []), last)


def npc_goods_line(npc: dict, last: str | None = None) -> str:
    """خطِ 'درباره‌ی کالاها' — اگه NPC کالا نداشته باشه (مثلاً دلالِ شایعات)، از شایعه استفاده می‌کنه."""
    pool = npc.get("about_goods") or npc.get("rumor", [])
    return _pick_no_repeat(pool, last)


