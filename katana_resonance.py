def katana_resonance_reaction(player: dict, old_res: int, new_res: int) -> str:
    """
    بعدِ هر تغییرِ Resonance تو داستانِ اصلی صدا زده می‌شه. فقط وقتی
    تغییر واقعاً «قابل‌توجه» باشه (رد شدن از آستانه‌ی Light/Void یا یه
    جهشِ بزرگِ یهویی) یه خطِ دیالوگ برمی‌گردونه؛ در غیرِ این‌صورت ""
    (تا هر انتخابِ کوچیکِ داستان اسپم دیالوگ نشه).
    """
    if old_res == new_res:
        return ""

    from quest_engine import resonance_label
    old_label = resonance_label(old_res)
    new_label = resonance_label(new_res)

    crossed_threshold = old_label != new_label
    big_jump = abs(new_res - old_res) >= BIG_JUMP_THRESHOLD
    if not (crossed_threshold or big_jump):
        return ""

    char_name = player.get("character", "")
    if not char_name:
        return ""

    from katana_personality import get_personality
    ptype = get_personality(player, char_name).get("type", "")

    pool = RESONANCE_LINES.get(ptype, _DEFAULT_LINES)
    key = _resonance_key(new_label)
    lines = pool.get(key) or _DEFAULT_LINES[key]
    if not lines:
        return ""
    return random.choice(lines)
