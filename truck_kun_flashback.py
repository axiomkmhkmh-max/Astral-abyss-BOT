REACTIONS = {
    "accept": {"label": "😌 قبولش کردم", "tag": "آرام"},
    "fight": {"label": "😤 نمی‌تونم قبول کنم", "tag": "سرکش"},
    "curious": {"label": "🤔 کنجکاوم بدونم چرا", "tag": "کنجکاو"},
}


def random_scene() -> dict:
    return random.choice(FLASHBACK_SCENES)


def scene_text(scene: dict) -> str:
    return (
        f"{scene['title']}\n\n"
        f"_{scene['text']}_\n\n"
        "چطور با این لحظه کنار میای؟"
    )


def apply_reaction(player: dict, scene_id: str, reaction_id: str) -> str:
    """فقط یه تگِ نمایشیِ فلیوردار رو پروفایل ذخیره می‌کنه — تاثیرِ مکانیکی نداره."""
    reaction = REACTIONS.get(reaction_id, REACTIONS["accept"])
    player["isekai_arrival_scene"] = scene_id
    player["isekai_arrival_temperament"] = reaction["tag"]
    return f"«{reaction['tag']}...» یه چیزی درونت این کلمه رو زمزمه کرد."
