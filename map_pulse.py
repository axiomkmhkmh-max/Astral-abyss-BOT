def _pick(pool: list[str]) -> str:
    return random.choice(pool) if pool else ""


def get_weather(map_name: str) -> dict:
    """هوای *مشترکِ* این نقشه — رو یه سند تو دیتابیس ذخیره می‌شه و
    هر چند ساعت می‌چرخه، پس همه‌ی بازیکن‌ها هم‌زمان یه هوای یکسون
    می‌بینن (نه یه رندومِ تازه به‌ازای هر بازدید)."""
    try:
        from database import system_col
        col = system_col()
        doc_id = f"map_weather:{map_name}"
        now = time.time()
        doc = col.find_one({"_id": doc_id})
        if not doc or doc.get("expires_at", 0) <= now:
            pool = WEATHER_POOL.get(map_name, _DEFAULT_WEATHER)
            weather = dict(random.choice(pool))
            hours = random.uniform(WEATHER_REFRESH_MIN_H, WEATHER_REFRESH_MAX_H)
            doc = {"_id": doc_id, "weather": weather, "expires_at": now + hours * 3600}
            col.update_one({"_id": doc_id}, {"$set": doc}, upsert=True)
        return doc["weather"]
    except Exception:
        pool = WEATHER_POOL.get(map_name, _DEFAULT_WEATHER)
        return random.choice(pool)


def weather_badge(map_name: str) -> str:
    w = get_weather(map_name)
    return f"{w['emoji']} **هوای {map_name} امروز: {w['name']}** — _{w['desc']}_"


_REACTIVE_VERB = {
    "boss_kill": "باسِ منطقه رو شکست داد",
    "legendary_kill": "یه دشمنِ لجندری رو از پا درآورد",
    "elite_kill": "یه دشمنِ نخبه رو شکار کرد",
}


def reactive_line(map_name: str) -> str | None:
    """اگه یه اتفاقِ نادرِ واقعی تو این نقشه همین اواخر افتاده باشه
    (از map_activity.py)، نبضِ شهر واقعاً بهش واکنش نشون می‌ده."""
    try:
        from map_activity import _doc as activity_doc, RARE_KINDS
        doc = activity_doc()
        events = doc["feed"].get(map_name, [])
    except Exception:
        return None

    now = time.time()
    rare = [e for e in events if e.get("kind") in RARE_KINDS and now - e.get("ts", 0) <= REACTIVE_WINDOW]
    if not rare:
        return None
    e = max(rare, key=lambda x: x["ts"])
    verb = _REACTIVE_VERB.get(e.get("kind"), "یه کارِ بزرگ کرد")
    actor = e.get("actor", "یه سالکِ ناشناس")
    return f"📣 همه‌ی شهر دارن حرف می‌زنن که **{actor}** همین امروز {verb} — هنوز حرفش رو زبون‌هاست!"


def king_personal_line(map_name: str, player: dict | None) -> str | None:
    """اگه بازیکن رابطه‌ی عمیقی با پادشاهِ این نقشه داشته باشه، گاهی
    خودِ پادشاه تو نبضِ شهر بهش اشاره می‌کنه — حسِ شناخته‌شدن."""
    if not player:
        return None
    try:
        import map_kings as mk
        king = mk.get_king(map_name)
        if not king:
            return None
        fav = mk.get_player_favor(player, map_name)
        tier = mk.get_tier(fav["favor"])
        if tier not in ("trusted", "exalted"):
            return None
        return f"👑 یکی از افرادِ {king['name']} از دور بهت سر تکون داد — انگار قبلاً اسمت رو شنیده."
    except Exception:
        return None


def pulse_line(map_name: str, player: dict | None = None) -> str:
    """یه خطِ نبضِ زنده برای این نقشه — لایه‌های اولویت‌دار: افسانه‌ای
    (نادر) → واکنشی (اگه اتفاقِ واقعی بود) → آگاه‌از‌پادشاه (اگه رابطه
    عمیق بود) → شایعه‌ی بین‌شهری → رویدادِ کمیاب → وابسته‌به‌ساعت →
    خطِ عمومیِ شهر.

    نکته‌ی مهم: هر لایه دقیقاً تویِ بازه‌ی احتمالیِ خودش چک می‌شه — اگه
    محتوایی نداشت (مثلاً هیچ اتفاقِ واقعی‌ای نبود)، مستقیم می‌ره سراغِ
    خطِ پیش‌فرضِ شهر، نه لایه‌ی بعدی؛ وگرنه احتمالِ لایه‌های بعدی به‌طورِ
    ناخواسته بالاتر از چیزی که تعریف شده می‌ره (چون roll هنوز تویِ
    بازه‌ی لایه‌ی قبلیه و شرطِ لایه‌ی بعدی رو هم قبول می‌کنه)."""
    roll = random.random()
    default = lambda: (
        _pick(PULSE_LINES.get(map_name, [])) or _pick(TIME_PULSE.get(_time_bucket(), []))
    )

    cursor = P_LEGENDARY
    if roll < cursor:
        return _pick(RARE_LEGENDARY_EVENTS.get(map_name, [])) or default()

    cursor += P_REACTIVE
    if roll < cursor:
        return reactive_line(map_name) or default()

    cursor += P_KING_AWARE
    if roll < cursor:
        return king_personal_line(map_name, player) or default()

    cursor += P_CROSS_RUMOR
    if roll < cursor:
        return _pick(CROSS_RUMORS.get(map_name, [])) or default()

    cursor += P_MICRO_EVENT
    if roll < cursor:
        return _pick(MICRO_EVENTS.get(map_name, [])) or default()

    cursor += P_TIME_PULSE
    if roll < cursor:
        return _pick(TIME_PULSE.get(_time_bucket(), [])) or default()

    return default()


def full_pulse_text(map_name: str, player: dict | None = None) -> str:
    """میانبرِ راحت برای هندلرها: خطِ هوا + یه خطِ نبضِ زنده، آماده‌ی
    چسبوندن به متنِ نقشه."""
    return f"{weather_badge(map_name)}\n{pulse_line(map_name, player)}"
