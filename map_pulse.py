def _pick(pool: list[str]) -> str:
    return random.choice(pool) if pool else ""


def pulse_line(map_name: str) -> str:
    """یه خطِ نبضِ زنده برای این نقشه — ترکیبی از خطوطِ اختصاصیِ شهر،
    رویدادهای کمیاب، و خطوطِ عمومیِ وابسته به ساعتِ روز."""
    roll = random.random()

    micro = MICRO_EVENTS.get(map_name, [])
    if micro and roll < MICRO_EVENT_CHANCE:
        return _pick(micro)

    if roll < MICRO_EVENT_CHANCE + TIME_PULSE_CHANCE:
        return _pick(TIME_PULSE.get(_time_bucket(), []))

    lines = PULSE_LINES.get(map_name)
    if lines:
        return _pick(lines)
    # فال‌بک برای نقشه‌ای که (فعلاً) دیتای اختصاصی نداره
    return _pick(TIME_PULSE.get(_time_bucket(), []))
