def _line(word: str, level: int | None, req: dict) -> str | None:
    desc = DESC.get(word)
    if not desc:
        return None
    need = req.get(word, 1)
    lock = f" 🔒 لول {need}" if (level is not None and need > level) else ""
    cd = ""
    try:
        import curse_system
        sec = curse_system.COOLDOWNS.get(word)
        if sec:
            cd = f" ⏳ کولداون {sec // 60} دقیقه"
    except Exception:
        pass
    return f"• `{word}` — {desc}{lock}{cd}"


def build_panel_messages(player: dict | None) -> list[str]:
    """لیستِ پیام‌های پنل رو می‌سازه (هرکدوم زیرِ سقفِ طولِ تلگرام)."""
    from bot import CATEGORIES, LEVEL_REQUIREMENTS, PRIVATE_COMMANDS  # lazy: جلوگیری از import حلقوی

    level = (player or {}).get("level", 1) if player else None
    cls = (player or {}).get("class") if player else None

    blocks: list[str] = []
    shown: set[str] = set()

    for title, words in GROUPS:
        lines = []
        for w in words:
            ln = _line(w, level, LEVEL_REQUIREMENTS)
            if ln:
                lines.append(ln)
                shown.add(w)
        if lines:
            blocks.append(f"**{title}**\n" + "\n".join(lines))

    # ─── بخشِ کلاسِ خودِ پلیر (فقط چیزهایی که بالا نیومده) ─────────
    if cls:
        extra = []
        for cat in CATEGORIES.values():
            if cat.get("class_only") == cls:
                for w in cat["buttons"]:
                    if w not in shown:
                        ln = _line(w, level, LEVEL_REQUIREMENTS)
                        if ln:
                            extra.append(ln)
                            shown.add(w)
        if extra:
            blocks.append("**✨ مخصوصِ کلاسِ تو**\n" + "\n".join(extra))

    blocks.append(QUICK_GAMES)

    # ─── اسلش‌کامندها از لیستِ واقعیِ ربات ──────────────────────
    cmds = [f"• `/{c.command}` — {c.description}" for c in PRIVATE_COMMANDS]
    blocks.append("**⌨️ اسلش‌کامندها**\n" + "\n".join(cmds))

    blocks.append("📚 توضیحِ کامل و عمیقِ هر بخش: /help")

    # ─── بسته‌بندیِ بلوک‌ها تو پیام‌ها (بدونِ شکستنِ وسطِ یه بلوک) ─
    messages: list[str] = []
    cur = "📖 **دستورات Astral Abyss**\nهمه‌چی رو با تایپِ همون کلمه انجام بده (کلمه‌ها رو می‌تونی لمس کنی و کپی کنی).\n"
    for b in blocks:
        if len(cur) + len(b) + 2 > _LIMIT:
            messages.append(cur.rstrip())
            cur = ""
        cur += ("\n" if cur else "") + b + "\n"
    if cur.strip():
        messages.append(cur.rstrip())
    return messages


async def cmd_commands_panel(msg: Message):
    from database import aget_player

    try:
        player = await aget_player(msg.from_user.id)
    except Exception:
        player = None
    for text in build_panel_messages(player):
        await msg.answer(text)


def register_commands_panel(dp: Dispatcher) -> None:
    dp.message.register(cmd_commands_panel, F.text.in_(TRIGGERS))
    dp.message.register(cmd_commands_panel, Command("commands"))
