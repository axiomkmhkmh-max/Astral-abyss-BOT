_SECTION_MAP = {key: (title, text) for key, title, text in HELP_SECTIONS}


def help_menu_kb() -> InlineKeyboardMarkup:
    rows = []
    row: list[InlineKeyboardButton] = []
    for key, title, _ in HELP_SECTIONS:
        row.append(InlineKeyboardButton(text=title, callback_data=f"help:{key}"))
        if len(row) == 2:
            rows.append(row)
            row = []
    if row:
        rows.append(row)
    return InlineKeyboardMarkup(inline_keyboard=rows)


def help_section_kb() -> InlineKeyboardMarkup:
    return InlineKeyboardMarkup(inline_keyboard=[
        [InlineKeyboardButton(text="🔙 بازگشت به لیستِ بخش‌ها", callback_data="help:menu")],
    ])


HELP_INTRO = (
    "📜 **راهنمای کاملِ ASTRAL ABYSS**\n\n"
    "یکی از بخش‌های زیر رو انتخاب کن تا توضیحِ کامل و صفر‌تا‌صدش رو ببینی — "
    "همه‌چیز از شروعِ بازی تا اقتصاد و PvP اینجا پوشش داده شده.\n\n"
    "هر وقت خواستی، همینجا دوباره `/help` بزن."
)


def register_help_handlers(dp: Dispatcher, bot: Bot):

    @dp.message(Command("help"))
    async def cmd_help(msg: Message):
        await msg.answer(HELP_INTRO, reply_markup=help_menu_kb())

    @dp.callback_query(F.data == "help:menu")
    async def cb_help_menu(cb: CallbackQuery):
        await cb.answer()
        await cb.message.edit_text(HELP_INTRO, reply_markup=help_menu_kb())

    @dp.callback_query(F.data.startswith("help:"))
    async def cb_help_section(cb: CallbackQuery):
        key = cb.data.split(":", 1)[1]
        if key == "menu":
            return  # هندلرِ بالا خودش می‌گیرتش
        entry = _SECTION_MAP.get(key)
        if entry is None:
            return await cb.answer("❌ بخش پیدا نشد.", show_alert=True)
        _, text = entry
        await cb.answer()
        await cb.message.edit_text(text, reply_markup=help_section_kb())

    print("✅ Help System Loaded Successfully")
